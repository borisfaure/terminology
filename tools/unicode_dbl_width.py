#!/usr/bin/env python3

"""
Generate src/bin/termptydbl.{c,h} from unicode files
used with ucd.all.flat.xml from
https://www.unicode.org/Public/UCD/latest/ucdxml/ucd.all.flat.zip
"""

import argparse
from collections import namedtuple
import xml.etree.ElementTree as ET

URange = namedtuple('unicode_range', ['width', 'start', 'end'])

# zero width code points below this are looked up in a bitmap
ZW_TABLE_END = 0x20000

def get_ranges(xmlfile):
    tree = ET.parse(xmlfile)
    root = tree.getroot()
    repertoire = root.find("{http://www.unicode.org/ns/2003/ucd/1.0}repertoire")
    chars = repertoire.findall("{http://www.unicode.org/ns/2003/ucd/1.0}char")

    ranges_basic = []
    ranges_emoji_double = []
    ranges_zero = []
    r_basic = URange('N', 0, 0)
    r_emoji_dbl = URange('N', 0, 0)
    r_zero = URange('N', 0, 0)
    for c in chars:
        ea = c.get('ea')
        if ea in ('Na', 'H'):
            ea = 'N'
        if ea in ('F'):
            ea = 'W'
        cp = c.get('cp')
        if not cp:
            continue
        cp = int(cp, 16)

        # zero width, as wcwidth() in glibc
        gc = c.get('gc')
        if (gc in ('Mn', 'Me') or c.get('hst') in ('V', 'T') or
                (gc == 'Cf' and cp != 0xAD and c.get('PCM') != 'Y')):
            zw = 'Z'
        else:
            zw = 'N'
        if zw != r_zero[0]:
            ranges_zero.append(r_zero)
            r_zero = URange(zw, cp, cp)
        else:
            r_zero = r_zero._replace(end=cp)

        # basic
        if ea != r_basic[0]:
            ranges_basic.append(r_basic)
            r_basic = URange(ea, cp, cp)
        else:
            r_basic = r_basic._replace(end=cp)

        # emoji as wide
        ext_pic = c.get('ExtPict')
        emoji = c.get('Emoji')
        if emoji == 'Y' and ext_pic == 'Y' and ea != 'A':
            ea = 'W'
        else:
            blk = c.get('blk')
            if blk == 'Misc_Pictographs':
                ea = 'W'
        if ea != r_emoji_dbl[0]:
            ranges_emoji_double.append(r_emoji_dbl)
            r_emoji_dbl = URange(ea, cp, cp)
        else:
            r_emoji_dbl = r_emoji_dbl._replace(end=cp)

    ranges_basic.append(r_basic)
    ranges_emoji_double.append(r_emoji_dbl)
    ranges_zero.append(r_zero)

    return (ranges_basic, ranges_emoji_double, ranges_zero)


def merge_ranges(ranges, is_same_width):
    res = []
    cur_range = ranges[0]
    for r in ranges:
        if is_same_width(r, cur_range):
            cur_range = cur_range._replace(end=r.end)
        else:
            res.append(cur_range)
            cur_range = r
    res.append(cur_range)
    return res

def skip_ranges(ranges, width_skipped):
    res = []
    for r in ranges:
        if r.width not in width_skipped:
            res.append(r)
    return res

def gen_header(mininum_codepoint, minimum_zero_width, high_zero_ranges,
               file_header):
    file_header.write(
"""/* XXX: Code generated by tool unicode_dbl_width.py */
#ifndef TERMINOLOGY_TERMPTY_DBL_H_
#define TERMINOLOGY_TERMPTY_DBL_H_ 1

Eina_Bool _termpty_is_wide(const Eina_Unicode g, Eina_Bool emoji_dbl_width);
Eina_Bool _termpty_is_ambigous_wide(const Eina_Unicode g, Eina_Bool emoji_dbl_width);
extern const unsigned char _termpty_zero_width_block[];
extern const unsigned int _termpty_zero_width_bits[][8];

static inline Eina_Bool
_termpty_is_wide_table(const Termpty *ty, const Eina_Unicode g, Eina_Bool emoji)
{
   return ty->termstate.cjk_ambiguous_wide
      ? _termpty_is_ambigous_wide(g, emoji)
      : _termpty_is_wide(g, emoji);
}

/* vs16: whether this codepoint is immediately followed by U+FE0F
 * (VARIATION SELECTOR-16). Only makes emoji-table-only codepoints wide
 * when EINA_TRUE; the base (genuinely wide) table is unaffected either
 * way. Callers writing a base character narrow-first (see
 * termpty_text_append()'s VS16 retro-widen) should pass EINA_FALSE and
 * apply the wide table's superset separately once VS16 is seen. */
static inline Eina_Bool
_termpty_is_dblwidth_get(const Termpty *ty, const Eina_Unicode g, Eina_Bool vs16)
{
   /* optimize for latin1 non-ambiguous */
""")
    file_header.write(f"   if (g <= 0x{mininum_codepoint:X})")
    file_header.write(
"""
     return EINA_FALSE;
   if (_termpty_is_wide_table(ty, g, EINA_FALSE))
     return EINA_TRUE;
   return ty->config->emoji_dbl_width && vs16 &&
      _termpty_is_wide_table(ty, g, EINA_TRUE);
}

/* Combining marks, format characters and Hangul medial vowels and final
 * consonants: they take no cell. */
static inline Eina_Bool
_termpty_is_zero_width_get(const Eina_Unicode g)
{
   const unsigned int *bits;

""")
    file_header.write(f"   if (g < 0x{minimum_zero_width:X})")
    file_header.write(
"""
     return EINA_FALSE;
""")
    file_header.write(f"   if (g >= 0x{ZW_TABLE_END:X})\n")
    file_header.write("     return ")
    file_header.write(" ||\n        ".join(
        f"((g >= 0x{r.start:X}) && (g <= 0x{r.end:X}))"
        for r in high_zero_ranges))
    file_header.write(";\n")
    file_header.write(
"""   bits = _termpty_zero_width_bits[_termpty_zero_width_block[g >> 8]];
   return (bits[(g >> 5) & 7] >> (g & 31)) & 1;
}

#endif
""")

def gen_ambigous(ranges_basic, ranges_emoji_double, file_source):
    def handle_ranges(ranges):
        def is_same_width(r1, r2):
            if r1.width == 'N':
                return r2.width == 'N'
            else:
                return r2.width in ('A', 'W')
        ranges = merge_ranges(ranges[1:], is_same_width)
        ranges = skip_ranges(ranges, ('N',))
        fallthrough = " EINA_FALLTHROUGH;"
        for idx, r in enumerate(ranges):
            if r.width == 'N':
                continue;
            if idx == len(ranges) -1:
                fallthrough = ""
            if r.start == r.end:
                file_source.write(f"           case 0x{r.start:X}:{fallthrough}\n")
            else:
                file_source.write(f"           case 0x{r.start:X} ... 0x{r.end:X}:{fallthrough}\n")

    file_source.write(
"""
__attribute__((const))
Eina_Bool
_termpty_is_ambigous_wide(Eina_Unicode g, Eina_Bool emoji_dbl_width)
{
   if (emoji_dbl_width)
     {
        switch (g)
          {
""")
    handle_ranges(ranges_emoji_double)
    file_source.write(
"""             return EINA_TRUE;
         }
     }
   else
     {
        switch (g)
          {
""")
    handle_ranges(ranges_basic)
    file_source.write(
"""             return EINA_TRUE;
          }
     }
   return EINA_FALSE;
}
""")


def gen_wide(ranges_basic, ranges_emoji_double, file_source):
    def handle_ranges(ranges):
        def is_same_width(r1, r2):
            if r1.width in ('N', 'A'):
                return r2.width in ('N', 'A')
            else:
                return r2.width == 'W'
        ranges = merge_ranges(ranges[1:], is_same_width)
        ranges = skip_ranges(ranges, ('N', 'A'))
        fallthrough = " EINA_FALLTHROUGH;"
        for idx, r in enumerate(ranges):
            if r.width in ('N', 'A'):
                continue;
            if idx == len(ranges) -1:
                fallthrough = ""
            if r.start == r.end:
                file_source.write(f"        case 0x{r.start:X}:{fallthrough}\n")
            else:
                file_source.write(f"        case 0x{r.start:X} ... 0x{r.end:X}:{fallthrough}\n")

    file_source.write(
"""
__attribute__((const))
Eina_Bool
_termpty_is_wide(Eina_Unicode g, Eina_Bool emoji_dbl_width)
{
   if (emoji_dbl_width)
     {
        switch (g)
          {
""")
    handle_ranges(ranges_emoji_double)
    file_source.write(
"""             return EINA_TRUE;
          }
     }
   else
     {
        switch (g)
          {
""")
    handle_ranges(ranges_basic)
    file_source.write(
"""             return EINA_TRUE;
          }
     }
   return EINA_FALSE;
}
""")


def zero_width_ranges(ranges_zero):
    ranges = merge_ranges(ranges_zero[1:], lambda r1, r2: r1.width == r2.width)
    return skip_ranges(ranges, ('N',))

def gen_zero_width(ranges_zero, file_source):
    bits = bytearray(ZW_TABLE_END // 8)
    for r in zero_width_ranges(ranges_zero):
        for cp in range(r.start, min(r.end + 1, ZW_TABLE_END)):
            bits[cp >> 3] |= 1 << (cp & 7)
    blocks = []
    block_of_page = []
    for page in range(ZW_TABLE_END >> 8):
        block = bytes(bits[page * 32:(page + 1) * 32])
        if block not in blocks:
            blocks.append(block)
        block_of_page.append(blocks.index(block))
    assert len(blocks) <= 256

    file_source.write(
"""
/* 256-bit block of each 256 code points below the table end */
const unsigned char _termpty_zero_width_block[] = {
""")
    for i in range(0, len(block_of_page), 16):
        line = ", ".join(f"{b}" for b in block_of_page[i:i + 16])
        file_source.write(f"   {line},\n")
    file_source.write(
"""};

const unsigned int _termpty_zero_width_bits[][8] = {
""")
    for block in blocks:
        words = [int.from_bytes(block[i:i + 4], 'little')
                 for i in range(0, 32, 4)]
        line = ", ".join(f"0x{w:08X}" for w in words)
        file_source.write(f"   {{ {line} }},\n")
    file_source.write("};\n")


def gen_c(ranges_basic, ranges_emoji_double, ranges_zero,
          file_header, file_source):
    mininum_codepoint = min(ranges_basic[0].end, ranges_emoji_double[0].end)
    zero = zero_width_ranges(ranges_zero)
    high_zero_ranges = [r for r in zero if r.end >= ZW_TABLE_END]
    assert all(r.start >= ZW_TABLE_END for r in high_zero_ranges)
    gen_header(mininum_codepoint, zero[0].start, high_zero_ranges,
               file_header)
    file_source.write(
"""/* XXX: Code generated by tool unicode_dbl_width.py */
#include "private.h"

#include <Elementary.h>
#include "termpty.h"
#include "termptydbl.h"
""")
    gen_ambigous(ranges_basic, ranges_emoji_double, file_source)
    gen_wide(ranges_basic, ranges_emoji_double, file_source)
    gen_zero_width(ranges_zero, file_source)

parser = argparse.ArgumentParser(description='Generate code handling different widths of unicode codepoints.')
parser.add_argument('xml', type=argparse.FileType('r'))
parser.add_argument('header', type=argparse.FileType('w'))
parser.add_argument('source', type=argparse.FileType('w'))

args = parser.parse_args()

(ranges_basic, ranges_emoji_double, ranges_zero) = get_ranges(args.xml)
gen_c(ranges_basic, ranges_emoji_double, ranges_zero,
      args.header, args.source)
