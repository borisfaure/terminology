#!/bin/sh
# Regenerate src/bin/keyin_keysyms.gperf, the keysym-name -> codepoint table
# looked up by keyin_keysym_codepoint(), from X11's keysymdef.h.  Only the
# keysyms with a Unicode mapping (the "U+XXXX" comment) are kept.
#
# tools/gen_keysyms.sh /usr/include/X11/keysymdef.h src/bin/keyin_keysyms.gperf

set -e

if [ $# -ne 2 ]; then
   echo "usage: $0 <keysymdef.h> <output>" >&2
   exit 1
fi

input=$1
output=$2

{
   echo "%{"
   echo "/* Generated by tools/gen_keysyms.sh; do not edit. */"
   echo "#include <string.h>"
   echo "#include \"keyin_keysyms.h\""
   echo "%}"
   echo "%struct-type"
   echo "%omit-struct-type"
   echo "%language=ANSI-C"
   echo "%readonly-tables"
   echo "%pic"
   echo "%define lookup-function-name keyin_keysym_lookup"
   echo "%define hash-function-name keyin_keysym_hash"
   echo "%define string-pool-name keyin_keysym_stringpool"
   echo "struct keyin_keysym { int name; uint32_t cp; };"
   echo "%%"
   awk '$1 == "#define" && $2 ~ /^XK_/ && $4 == "/*" && \
        $5 ~ /^U\+[0-9A-Fa-f]+$/ \
        { print substr($2, 4) ", 0x" tolower(substr($5, 3)) }' "$input" \
      | LC_ALL=C sort
} > "$output"
